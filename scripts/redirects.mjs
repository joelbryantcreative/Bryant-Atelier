const hostRule = (hosts, rows) =>
  hosts.flatMap((h) =>
    rows.map(([from, to]) => ({
      source: from,
      has: [{ type: "host", value: h }],
      destination: NEW + to,
      statusCode: 301,
    }))
  );

const redirects = [
  { source: "/:path*", has: [{ type: "host", value: "www." + newHost }], destination: NEW + "/:path*", statusCode: 301 },
  ...hostRule(lineageHosts, lineage),
  ...hostRule(convertHosts, convert),
  ...sameHost.map(([from, to]) => ({ source: from, destination: to, statusCode: 301 })),
];

const vercel = {
  $schema: "https://openapi.vercel.sh/vercel.json",
  framework: null,
  buildCommand: "npm run build",
  outputDirectory: "_site",
  cleanUrls: true,
  trailingSlash: true,
  redirects,
  headers: [
    {
      source: "/(.*)",
      headers: [
        { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains; preload" },
        { key: "X-Content-Type-Options", value: "nosniff" },
        { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
      ],
    },
    { source: "/img/(.*)", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
    { source: "/assets/(.*)", headers: [{ key: "Cache-Control", value: "public, max-age=604800" }] },
    { source: "/assets/fonts/(.*)", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
  ],
};
writeFileSync(new URL("../vercel.json", import.meta.url), JSON.stringify(vercel, null, 2) + "\n");

const table = (domain, rows) =>
  `| Old URL | New URL | Notes |\n|---|---|---|\n` +
  rows.map(([f, t, n]) => `| \`https://${domain}${f}\` | \`${NEW}${t}\` | ${n} |`).join("\n");

